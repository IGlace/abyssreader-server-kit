// Command notices writes THIRD_PARTY_NOTICES for a Go program: the licence text of Go itself
// and of every module linked into the program, from the module cache. The image build and CI
// run it, so the file never goes stale. It fails when a module has no licence file or its
// licence is one the kit may not link (GPL, LGPL, AGPL, SSPL).
//
//	go run ./scripts/notices -o THIRD_PARTY_NOTICES ./cmd/abyssreader-server
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
)

type module struct{ Path, Version, Dir string }

func main() {
	out := flag.String("o", "", "write here instead of stdout")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: notices [-o file] <main package>")
		os.Exit(2)
	}
	mods, err := linkedModules(flag.Arg(0))
	if err == nil {
		var b bytes.Buffer
		if err = write(&b, mods); err == nil {
			if *out == "" {
				_, err = os.Stdout.Write(b.Bytes())
			} else {
				err = os.WriteFile(*out, b.Bytes(), 0o644)
			}
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

// linkedModules lists the modules whose packages the program imports, without the main module.
func linkedModules(pkg string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-f",
		`{{if not .Standard}}{{with .Module}}{{if not .Main}}{{.Path}}{{"\t"}}{{.Version}}{{"\t"}}{{.Dir}}{{end}}{{end}}{{end}}`, pkg)
	cmd.Stderr = os.Stderr
	b, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	seen := map[string]bool{}
	var mods []module
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if len(f) != 3 || seen[f[0]] {
			continue
		}
		seen[f[0]] = true
		mods = append(mods, module{f[0], f[1], f[2]})
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

var licenceFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice)([-._].*)?$`)

// forbidden finds a licence the kit may not link into its binary, by its title on a line of its
// own (as the licence texts start), so a text that merely mentions one (MPL-2.0's "Secondary
// License" list, for example) does not count.
var forbidden = regexp.MustCompile(`(?im)^[\s#*]*(GNU (AFFERO |LESSER |LIBRARY )?GENERAL PUBLIC LICENSE|SERVER SIDE PUBLIC LICENSE)\s*$`)

func write(w io.Writer, mods []module) error {
	fmt.Fprintln(w, "Third-party notices for abyssreader-server")
	fmt.Fprintln(w, "Generated by scripts/notices from the modules linked into the program.")
	goLicence, err := goLicence()
	if err != nil {
		return fmt.Errorf("Go's own licence: %w", err)
	}
	section(w, "Go "+runtime.Version()+" (the Go runtime and standard library)", "LICENSE", goLicence)
	var errs []error
	for _, m := range mods {
		texts, err := licences(m.Dir)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", m.Path, err))
			continue
		}
		for _, t := range texts {
			if forbidden.Match(t.text) {
				errs = append(errs, fmt.Errorf("%s %s: %s is a licence the kit may not link (GPL, LGPL, AGPL or SSPL)", m.Path, m.Version, t.name))
			}
			section(w, m.Path+" "+m.Version, t.name, t.text)
		}
	}
	return errors.Join(errs...)
}

// goLicence reads Go's LICENSE from GOROOT (some packagers, Homebrew among them, keep it one
// folder up).
func goLicence() ([]byte, error) {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return nil, err
	}
	root := strings.TrimSpace(string(out))
	b, err := os.ReadFile(filepath.Join(root, "LICENSE"))
	if errors.Is(err, os.ErrNotExist) {
		b, err = os.ReadFile(filepath.Join(root, "..", "LICENSE"))
	}
	return b, err
}

type text struct {
	name string
	text []byte
}

func licences(dir string) ([]text, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []text
	for _, e := range entries {
		if e.IsDir() || !licenceFile.MatchString(e.Name()) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		out = append(out, text{e.Name(), b})
	}
	if len(out) == 0 {
		return nil, errors.New("no licence file")
	}
	return out, nil
}

func section(w io.Writer, title, file string, body []byte) {
	fmt.Fprintf(w, "\n%s\n%s (%s)\n%s\n\n", strings.Repeat("=", 78), title, file, strings.Repeat("=", 78))
	w.Write(bytes.TrimRight(body, "\n"))
	fmt.Fprintln(w)
}
